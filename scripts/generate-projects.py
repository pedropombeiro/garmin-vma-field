"""Regenerate the three projects from the reviewed device allowlist."""

import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
DEVICES = (ROOT / "config/devices.txt").read_text().split()
APPS = {
    "live": ("LiveApp", "VMA", "79b72ed936134e91aa42e73f316da54b"),
    "lap": ("LapApp", "Lap VMA", "9e738293a4ae46eb8ec964739ccdc8aa"),
    "pace": ("PaceApp", "VMA pace range", "b4920449a44341cfa79e63353de21b86"),
}

for field, (entry, name, app_id) in APPS.items():
    app = ROOT / "apps" / field
    resources = app / "resources"
    resources.mkdir(parents=True, exist_ok=True)
    # Each device has its own required launcher size. Keep one SVG source and
    # emit correctly sized copies instead of relying on compiler upscaling.
    device_root = Path.home() / "Library/Application Support/Garmin/ConnectIQ/Devices"
    overrides = []
    for device in DEVICES:
        profile = json.loads((device_root / device / "compiler.json").read_text())
        icon = profile["launcherIcon"]
        width, height = icon["width"], icon["height"]
        directory = ROOT / "icons" / f"{width}x{height}"
        directory.mkdir(parents=True, exist_ok=True)
        svg = (
            (ROOT / "resources/icon.svg")
            .read_text()
            .replace('width="30" height="30"', f'width="{width}" height="{height}"')
        )
        (directory / "icon.svg").write_text(svg)
        (directory / "drawables.xml").write_text(
            '<resources><drawables><bitmap id="LauncherIcon" filename="icon.svg"/></drawables></resources>\n'
        )
        overrides.append(
            f"{device}.resourcePath = $(base.resourcePath);../../icons/{width}x{height}"
        )
    products = "\n".join(f'            <iq:product id="{d}"/>' for d in DEVICES)
    permission = '<iq:uses-permission id="FitContributor"/>' if field != "pace" else ""
    (app / "manifest.xml").write_text(f'''<?xml version="1.0"?>
<!-- Generated by scripts/generate-projects.py. -->
<iq:manifest xmlns:iq="http://www.garmin.com/xml/connectiq" version="3">
    <iq:application entry="{entry}" id="{app_id}" launcherIcon="@Drawables.LauncherIcon"
        minApiLevel="3.2.0" name="@Strings.AppName" type="datafield" version="0.1.0">
        <iq:products>
{products}
        </iq:products>
        <iq:permissions>{permission}</iq:permissions>
        <iq:languages><iq:language>eng</iq:language></iq:languages>
        <iq:barrels/>
    </iq:application>
</iq:manifest>
''')
    excludes = ";".join(f"{other}Test" for other in APPS if other != field)
    (app / "monkey.jungle").write_text(
        f"""project.manifest = manifest.xml
base.sourcePath = ../../source;source;../../tests
base.resourcePath = ../../resources;resources
base.excludeAnnotations = {excludes}
"""
        + "\n".join(overrides)
        + "\n"
    )
    extra = ""
    if field == "pace":
        extra = """
    <properties>
        <property id="lowPercent" type="float">75.0</property>
        <property id="highPercent" type="float">88.0</property>
    </properties>
    <settings>
        <setting propertyKey="@Properties.lowPercent" title="@Strings.LowPercent">
            <settingConfig type="numeric" min="1" max="300"/>
        </setting>
        <setting propertyKey="@Properties.highPercent" title="@Strings.HighPercent">
            <settingConfig type="numeric" min="1" max="300"/>
        </setting>
    </settings>"""
    (resources / "resources.xml").write_text(f"""<resources>
    <strings><string id="AppName">{escape(name)}</string></strings>{extra}
</resources>
""")
    if field != "pace":
        flags = (
            'displayInChart="true" chartTitle="@Strings.LiveChart" fillColor="#00AAFF"'
            if field == "live"
            else 'displayInActivityLaps="true"'
        )
        label = "LiveLabel" if field == "live" else "LapLabel"
        (resources / "fitfields.xml").write_text(f"""<resources>
    <fitContributions>
        <fitField id="0" {flags} sortOrder="0" precision="0"
            dataLabel="@Strings.{label}" unitLabel="@Strings.Percent"/>
    </fitContributions>
</resources>
""")
